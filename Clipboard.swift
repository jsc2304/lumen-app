import AppKit

/// Clipboard history: polls the pasteboard, keeps the last 500 entries (text, links, colors, files, images)
/// on disk, plus every pinned one.
final class Clipboard {
    static let shared = Clipboard()

    enum Kind: String { case text = "Text", link = "Link", color = "Color", file = "File", image = "Image" }

    struct Entry: Codable {
        var id = UUID()
        var text: String? = nil
        var image: String? = nil    // PNG file name in imagesDir
        var files: [String]? = nil  // paths of copied files
        var date = Date()
        // Everything below is optional, so clipboard.json from older versions still loads.
        var pinned: Bool? = nil
        var app: String? = nil      // frontmost app at capture time
        var bundleID: String? = nil

        var isPinned: Bool { pinned == true }

        var kind: Kind {
            if files != nil { return .file }
            if image != nil { return .image }
            guard let text else { return .text }
            return Clipboard.link(text) != nil ? .link : Clipboard.color(text) != nil ? .color : .text
        }

        var title: String {
            if let files, let first = files.first {
                let name = URL(fileURLWithPath: first).lastPathComponent
                return files.count > 1 ? "\(name) and \(files.count - 1) more" : name
            }
            guard let text else { return "Image" }
            // The first line, at most 200 characters: a huge single-line copy would make every row heavy.
            return String(text.drop(while: \.isWhitespace).prefix(200).prefix(while: { !$0.isNewline }))
        }
    }

    static let limit = 500           // unpinned entries; pinned ones come on top
    static let previewLimit = 20_000 // characters shown in the detail pane, so a huge copy cannot stall it
    static let textLimit = 1_000_000 // UTF-8 bytes; a larger text copy is not stored

    // Password managers and other apps mark secrets and throwaway data with these types (nspasteboard.org);
    // such items are never stored.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb"]
    private let imagesDir = Store.dir.appendingPathComponent("clipboard")
    private var entries: [Entry] = Store.load("clipboard.json") ?? []
    private var thumbnails: [String: NSImage] = [:]
    private var sizes: [String: String] = [:]
    // Per entry, what is too slow to work out again on every keystroke. Dropped when the entry moves or goes.
    private var rendered: [UUID: (kind: Kind, icon: Icon, detail: Detail)] = [:]
    // clipboard.json is written at most every half second, encoded off the main thread from a snapshot.
    private let disk = DispatchQueue(label: "Lumen clipboard history")
    private var saving = false
    private let relative = RelativeDateTimeFormatter()
    private var lastChange = NSPasteboard.general.changeCount
    private var paused = false
    // Paste Sequentially hands out entries copied after this moment, oldest first. Not saved: a new launch starts a new sequence.
    private var cursor = Date.distantPast

    private init() { cursor = entries.first?.date ?? .distantPast }

    var count: Int { entries.count }

    func start() {
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        watchScreenshots()
        // A change from the last half second (a cleared history too) must not be lost on quit.
        NotificationCenter.default.addObserver(forName: NSApplication.willTerminateNotification, object: nil, queue: .main) { [self] _ in
            let snapshot = entries, pending = saving
            disk.sync { if pending { Store.save(snapshot, "clipboard.json") } }   // also waits for a write in progress
        }
    }

    // MARK: Screenshots

    private let screenshots = NSMetadataQuery()
    private var seenScreenshots: Set<String> = []

    /// Screenshots saved as files (⌘⇧3/4/5) never touch the pasteboard. Spotlight tags them with
    /// kMDItemIsScreenCapture wherever they are saved, so a live query adds each new one as an image entry.
    private func watchScreenshots() {
        screenshots.predicate = NSPredicate(format: "kMDItemIsScreenCapture == 1 AND %K >= %@",
                                            NSMetadataItemFSCreationDateKey, Date() as NSDate)
        screenshots.searchScopes = [NSMetadataQueryLocalComputerScope]
        for name in [Notification.Name.NSMetadataQueryDidFinishGathering, .NSMetadataQueryDidUpdate] {
            NotificationCenter.default.addObserver(forName: name, object: screenshots, queue: .main) { [weak self] _ in
                self?.addScreenshots()
            }
        }
        screenshots.start()
    }

    private func addScreenshots() {
        screenshots.disableUpdates()
        defer { screenshots.enableUpdates() }
        for case let item as NSMetadataItem in screenshots.results {
            guard let path = item.value(forAttribute: NSMetadataItemPathKey) as? String, !seenScreenshots.contains(path),
                  let data = try? Data(contentsOf: URL(fileURLWithPath: path)),
                  let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) else { continue }
            seenScreenshots.insert(path)
            let name = UUID().uuidString + ".png"
            try? png.write(to: imagesDir.appendingPathComponent(name))
            add(Entry(image: name, app: "Screenshot", bundleID: "com.apple.screencaptureui"))
        }
    }

    // MARK: Capture

    private func poll() {
        let pb = NSPasteboard.general
        guard !paused, pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if Self.isSecret(pb.types ?? []) { return }
        let app = NSWorkspace.shared.frontmostApplication
        var entry = Entry(app: app?.localizedName, bundleID: app?.bundleIdentifier)
        // Files first: Finder also puts the file names on the pasteboard as text.
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            entry.files = urls.map(\.path)
        } else if let text = pb.string(forType: .string), text.utf8.count <= Self.textLimit,
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            entry.text = text
        } else if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff),
                  let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) {
            let name = UUID().uuidString + ".png"
            try? png.write(to: imagesDir.appendingPathComponent(name))
            entry.image = name
        } else {
            return
        }
        add(entry)
    }

    private func add(_ entry: Entry) {
        let result = Self.adding(entry, to: entries, cap: Self.limit)
        entries = result.kept
        forget(result.dropped)
        // Copies of the same text or files are gone too, and a moved entry shows a new date.
        let ids = Set(entries.map(\.id))
        rendered = rendered.filter { ids.contains($0.key) && $0.key != entry.id }
        save()
    }

    private func save() {
        guard !saving else { return }
        saving = true
        later(0.5) { [self] in
            saving = false
            let snapshot = entries
            disk.async { Store.save(snapshot, "clipboard.json") }
        }
    }

    /// Deletes what the entries leave behind on disk and in the caches.
    private func forget(_ gone: [Entry]) {
        for e in gone {
            rendered[e.id] = nil
            guard let image = e.image else { continue }
            try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(image))
            thumbnails[image] = nil
            sizes[image] = nil
        }
    }

    /// Deletes everything; with `keepingPinned` the pinned entries stay.
    func clear(keepingPinned: Bool = false) {
        let kept = keepingPinned ? entries.filter(\.isPinned) : []
        forget(entries.filter { e in !kept.contains { $0.id == e.id } })
        entries = kept
        save()
    }

    // MARK: Commands

    func commands() -> [Item] {
        [.command("cmd.clipboard", "Clipboard History", icon: "doc.on.clipboard",
                  keywords: ["paste", "copy", "zwischenablage"], closes: false) { [self] in
            Launcher.shared.push(.list(ListSpec(title: "Clipboard History", placeholder: "Search clipboard history…", showsDetail: true) { [weak self] in
                self?.items(matching: $0) ?? []
            }))
        },
         .command("clip.paste-sequentially", "Paste Sequentially", kind: "Clipboard", icon: "list.number",
                  keywords: ["paste", "queue", "order", "sequence", "einfügen", "reihenfolge"]) { [self] in pasteNext() },
         .command("clip.reset-sequence", "Reset Paste Sequence", kind: "Clipboard", icon: "arrow.counterclockwise",
                  keywords: ["paste", "sequence", "restart", "zurücksetzen"]) { [self] in
            poll()   // an entry copied a moment ago is not in the history yet
            cursor = entries.first?.date ?? .distantPast
            HUD.show("Paste Sequence Reset")
        }]
    }

    /// Pastes the next entry in copy order without moving it in the history.
    private func pasteNext() {
        poll()
        guard let next = Self.next(after: cursor, in: entries) else { HUD.show("End of Paste Sequence"); return }
        cursor = next.date
        put(next)
        later { AX.key(9, .maskCommand) }
    }

    // MARK: List

    private func items(matching query: String) -> [Item] {
        let found = entries.filter { Self.matches($0, query, kind: rendering($0).kind) }
        let list = found.filter(\.isPinned) + found.filter { !$0.isPinned }
        let hasPins = list.first?.isPinned == true
        return list.map { item($0).inSection($0.isPinned ? "Pinned" : hasPins ? "History" : "") }
    }

    private func rendering(_ e: Entry) -> (kind: Kind, icon: Icon, detail: Detail) {
        if let r = rendered[e.id] { return r }
        let kind = e.kind
        let r = (kind: kind, icon: icon(e, kind), detail: detail(e, kind))
        rendered[e.id] = r
        return r
    }

    private func item(_ e: Entry) -> Item {
        let r = rendering(e)
        var actions = [
            Action(title: "Paste", icon: "doc.on.clipboard") { [weak self] in self?.paste(e) },
            Action(title: "Copy to Clipboard", icon: "doc.on.doc") { [weak self] in
                self?.write(e)
                HUD.show("Copied to Clipboard")
            },
            Action(title: e.isPinned ? "Unpin Entry" : "Pin Entry", icon: e.isPinned ? "pin.slash" : "pin",
                   shortcut: Shortcut([.command, .shift], "p"), closes: false) { [weak self] in self?.togglePin(e) },
        ]
        if r.kind == .link, let url = e.text.flatMap(Self.link) {
            actions.append(Action(title: "Open Link", icon: "link", shortcut: Shortcut(.command, "o")) { NSWorkspace.shared.open(url) })
        } else if let files = e.files {
            actions.append(Action(title: files.count > 1 ? "Open Files" : "Open File", icon: "folder", shortcut: Shortcut(.command, "o")) {
                files.forEach { NSWorkspace.shared.open(URL(fileURLWithPath: $0)) }
            })
        }
        actions += [
            Action(title: "Delete Entry", icon: "trash", shortcut: Shortcut(.control, "x"), destructive: true, closes: false) {
                [weak self] in self?.delete(e)
            },
            Action(title: "Delete All Entries", icon: "trash.slash", shortcut: Shortcut([.control, .shift], "x"), destructive: true) {
                [weak self] in
                if confirm("Delete all clipboard entries except the pinned ones? This cannot be undone.") { self?.clear(keepingPinned: true) }
            },
        ]
        return Item(id: e.id.uuidString, title: e.title, subtitle: relative.localizedString(for: e.date, relativeTo: Date()),
                    kind: r.kind.rawValue, icon: r.icon, track: false, actions: actions, detail: r.detail)
    }

    private func icon(_ e: Entry, _ kind: Kind) -> Icon {
        switch kind {
        case .image: return .image(picture(e.image ?? ""))
        case .file: return .image(NSWorkspace.shared.icon(forFile: e.files?.first ?? ""))
        case .color: return e.text.flatMap(Self.color).map(Icon.color) ?? .symbol("paintpalette")
        case .link: return .symbol("link")
        case .text: return .symbol("doc.text")
        }
    }

    private func detail(_ e: Entry, _ kind: Kind) -> Detail {
        var d = Detail(metadata: [("Type", kind.rawValue)])
        if let files = e.files {
            d.markdown = Self.escaped(files.joined(separator: "\n"))
        } else if let text = e.text {
            let characters = text.count
            d.markdown = Self.escaped(String(text.prefix(Self.previewLimit))) + (characters > Self.previewLimit ? "\n\n…" : "")
            d.metadata += [("Characters", "\(characters)"), ("Words", "\(text.split(whereSeparator: \.isWhitespace).count)")]
            if kind == .color, let color = Self.color(text) { d.image = Self.swatch(color) }
        } else if let image = e.image {
            d.image = picture(image)
            d.metadata.append(("Dimensions", dimensions(image)))
        }
        if let app = e.app { d.metadata.append(("Source app", app)) }
        d.metadata.append(("Copied", e.date.formatted(date: .abbreviated, time: .shortened)))
        return d
    }

    private func picture(_ name: String) -> NSImage {
        if let cached = thumbnails[name] { return cached }
        let image = NSImage(contentsOf: imagesDir.appendingPathComponent(name)) ?? NSImage()
        thumbnails[name] = image
        return image
    }

    /// Pixel size from the PNG header, without decoding the image.
    private func dimensions(_ name: String) -> String {
        if let cached = sizes[name] { return cached }
        var text = "Unknown"
        if let source = CGImageSourceCreateWithURL(imagesDir.appendingPathComponent(name) as CFURL, nil),
           let p = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
           let w = p[kCGImagePropertyPixelWidth] as? Int, let h = p[kCGImagePropertyPixelHeight] as? Int {
            text = "\(w) × \(h)"
        }
        sizes[name] = text
        return text
    }

    private static func swatch(_ color: NSColor) -> NSImage {
        NSImage(size: NSSize(width: 200, height: 60), flipped: false) { rect in
            color.setFill()
            NSBezierPath(roundedRect: rect, xRadius: 8, yRadius: 8).fill()
            return true
        }
    }

    // MARK: Row actions

    private func togglePin(_ e: Entry) {
        guard let i = entries.firstIndex(where: { $0.id == e.id }) else { return }
        entries[i].pinned = entries[i].isPinned ? nil : true
        save()
        Launcher.shared.reload()
    }

    private func delete(_ e: Entry) {
        forget([e])
        entries.removeAll { $0.id == e.id }
        save()
        Launcher.shared.reload()
    }

    /// Puts the entry on the pasteboard without recording it again.
    private func put(_ e: Entry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let files = e.files {
            pb.writeObjects(files.map { URL(fileURLWithPath: $0) as NSURL })
        } else if let text = e.text {
            pb.setString(text, forType: .string)
        } else if let image = e.image, let data = try? Data(contentsOf: imagesDir.appendingPathComponent(image)) {
            pb.setData(data, forType: .png)
        }
        lastChange = pb.changeCount
    }

    /// Puts the entry on the pasteboard and moves it to the top.
    private func write(_ e: Entry) {
        put(e)
        var moved = e
        moved.date = Date()
        add(moved)
    }

    private func paste(_ e: Entry) {
        write(e)
        later { AX.key(9, .maskCommand) }
    }

    /// Pastes text into the frontmost app; the text also lands in the history.
    func paste(text: String) {
        copyToClipboard(text)
        later { AX.key(9, .maskCommand) }
    }

    /// Copies the frontmost app's selection with ⌘C, hands it over, then puts the old clipboard back, all of it.
    func captureSelection(_ done: @escaping (String?) -> Void) {
        let pb = NSPasteboard.general
        let saved = Self.saveItems()
        let before = pb.changeCount
        paused = true
        later(0.1) {
            AX.key(8, .maskCommand)
            later(0.25) {
                let copied = pb.changeCount
                let text = copied != before ? pb.string(forType: .string) : nil
                if copied != before { Self.restore(saved, unlessChangedSince: copied) }
                self.lastChange = pb.changeCount
                self.paused = false
                done(text)
            }
        }
    }
}

// MARK: Borrowing the pasteboard (AI commands here, keyword expansion in Snippets.swift)

extension Clipboard {
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")

    /// Copies of every pasteboard item with all its types, so putting them back keeps images, files, rich text
    /// and the concealed/transient markers of password managers.
    static func saveItems() -> [NSPasteboardItem] {
        (NSPasteboard.general.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types { if let data = item.data(forType: type) { copy.setData(data, forType: type) } }
            return copy
        }
    }

    /// Writes items marked transient, so clipboard managers (this one too) do not record them as a new copy.
    /// Returns the changeCount right after.
    @discardableResult
    static func writeTransient(_ items: [NSPasteboardItem]) -> Int {
        let pb = NSPasteboard.general
        items.first?.setString("", forType: transient)
        pb.clearContents()
        pb.writeObjects(items)
        return pb.changeCount
    }

    /// Puts saved items back, unless something was copied since `changeCount`: the user's newer copy wins.
    static func restore(_ items: [NSPasteboardItem], unlessChangedSince changeCount: Int) {
        if NSPasteboard.general.changeCount == changeCount { writeTransient(items) }
    }
}

// MARK: Pure helpers (checked in checks/CheckClipboard.swift)

extension Clipboard {
    static func isSecret(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        types.contains { skippedTypes.contains($0.rawValue) }
    }

    /// Inserts `entry` at the top. The same text or files copied before move up instead of repeating, and a pin carries
    /// over. Beyond `cap` unpinned entries the oldest drop out.
    static func adding(_ entry: Entry, to entries: [Entry], cap: Int) -> (kept: [Entry], dropped: [Entry]) {
        func same(_ e: Entry) -> Bool {
            e.id == entry.id || (entry.text != nil && e.text == entry.text) || (entry.files != nil && e.files == entry.files)
        }
        var added = entry
        if entries.contains(where: { same($0) && $0.isPinned }) { added.pinned = true }
        var kept = [added], dropped: [Entry] = []
        var unpinned = added.isPinned ? 0 : 1
        for e in entries where !same(e) {
            if e.isPinned || unpinned < cap {
                kept.append(e)
                if !e.isPinned { unpinned += 1 }
            } else {
                dropped.append(e)
            }
        }
        return (kept, dropped)
    }

    /// The entry Paste Sequentially hands out next: the oldest one copied after `cursor`.
    static func next(after cursor: Date, in entries: [Entry]) -> Entry? {
        entries.filter { $0.date > cursor }.min { $0.date < $1.date }
    }

    /// Search matches the content, the type name and the source app. Pass `kind` when it is already known.
    static func matches(_ e: Entry, _ query: String, kind: Kind? = nil) -> Bool {
        query.isEmpty || [e.text, e.files?.joined(separator: "\n"), (kind ?? e.kind).rawValue, e.app]
            .contains { $0?.localizedCaseInsensitiveContains(query) ?? false }
    }

    /// A single URL: a scheme plus a host (or mailto:), no spaces.
    static func link(_ text: String) -> URL? {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.isEmpty, !t.contains(where: \.isWhitespace), let url = URL(string: t), let scheme = url.scheme, !scheme.isEmpty
        else { return nil }
        return url.host?.isEmpty == false || scheme == "mailto" ? url : nil
    }

    private static let rgbPattern = try! NSRegularExpression(
        pattern: #"^rgba?\(\s*(\d{1,3})\s*[,\s]\s*(\d{1,3})\s*[,\s]\s*(\d{1,3})\s*(?:[,/]\s*(\d*\.?\d+)(%?)\s*)?\)$"#)

    /// #rgb, #rgba, #rrggbb, #rrggbbaa, rgb(r, g, b) and rgba(r, g, b, a) as the whole text.
    static func color(_ text: String) -> NSColor? {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        if t.hasPrefix("#") {
            var hex = String(t.dropFirst())
            guard hex.allSatisfy(\.isHexDigit) else { return nil }
            if hex.count == 3 || hex.count == 4 { hex = hex.map { "\($0)\($0)" }.joined() }
            guard hex.count == 6 || hex.count == 8, let v = UInt64(hex, radix: 16) else { return nil }
            let rgb = hex.count == 8 ? v >> 8 : v
            let alpha = hex.count == 8 ? v & 255 : 255
            return NSColor(srgbRed: CGFloat(rgb >> 16 & 255) / 255, green: CGFloat(rgb >> 8 & 255) / 255,
                           blue: CGFloat(rgb & 255) / 255, alpha: CGFloat(alpha) / 255)
        }
        let s = t as NSString
        guard let m = rgbPattern.firstMatch(in: t, range: NSRange(location: 0, length: s.length)) else { return nil }
        let rgb = (1...3).map { Int(s.substring(with: m.range(at: $0))) ?? 256 }
        guard rgb.allSatisfy({ $0 <= 255 }) else { return nil }
        var alpha = 1.0
        if m.range(at: 4).location != NSNotFound {
            alpha = (Double(s.substring(with: m.range(at: 4))) ?? 1) / (m.range(at: 5).length > 0 ? 100 : 1)
        }
        return NSColor(srgbRed: CGFloat(rgb[0]) / 255, green: CGFloat(rgb[1]) / 255, blue: CGFloat(rgb[2]) / 255,
                       alpha: CGFloat(min(max(alpha, 0), 1)))
    }

    /// Backslash-escapes ASCII punctuation, so the detail pane (inline Markdown) shows the text exactly as copied.
    static func escaped(_ s: String) -> String {
        s.reduce(into: "") { out, c in
            if c.isASCII, c.isPunctuation || c.isSymbol { out.append("\\") }
            out.append(c)
        }
    }
}
